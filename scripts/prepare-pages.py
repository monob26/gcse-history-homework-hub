"""Copy plain static assets for either existing Pages URL; no application build."""

import argparse
import json
from pathlib import Path
import re
import shutil
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]


def test_config(filename):
    config = json.loads(filename.read_text())
    required = {'supabaseUrl', 'publishableKey', 'teacherRedirectUrl'}
    if not isinstance(config, dict) or set(config) != required:
        raise ValueError('Test config must contain exactly ' + ', '.join(sorted(required)))
    if not all(isinstance(value, str) for value in config.values()):
        raise ValueError('Test config values must be strings')
    project = urlsplit(config['supabaseUrl'])
    current = (ROOT / 'shared/config.js').read_text()
    if (project.scheme != 'https' or not project.hostname
            or not re.fullmatch(r'[a-z0-9]{20}\.supabase\.co', project.hostname)
            or project.username or project.password or project.port
            or project.path not in ('', '/') or project.query or project.fragment):
        raise ValueError('Test Supabase URL must be a hosted project HTTPS origin')
    if project.hostname in current:
        raise ValueError('Test deployment must use a different Supabase project')
    if not re.fullmatch(r'sb_publishable_[A-Za-z0-9_-]+', config['publishableKey']):
        raise ValueError('Use a public sb_publishable_ key; never a secret/service-role key')
    if config['publishableKey'] in current:
        raise ValueError('Test deployment must use its own project publishable key')
    redirect = urlsplit(config['teacherRedirectUrl'])
    if (redirect.scheme != 'https' or not redirect.hostname or redirect.username
            or redirect.password or redirect.query or redirect.fragment):
        raise ValueError('Test teacher redirect must be an HTTPS URL without credentials')
    if config['teacherRedirectUrl'].rstrip('/') in current:
        raise ValueError('Test teacher redirect must differ from the current teacher URL')
    return '// Public test-project configuration; generated during staging.\n' + (
        'window.HISTORY_CONFIG = Object.freeze(' + json.dumps(config, indent=2) + ');\n'
    )


def entry(page):
    source = (ROOT / page / "index.html").read_text()
    source = source.replace('../shared/', './shared/')
    source = source.replace('./styles.css', f'./{page}/styles.css')
    source = source.replace('./app.js', f'./{page}/app.js')
    source = source.replace('./captcha.js', f'./{page}/captcha.js')
    if page == 'teacher':
        for asset in ['quiz-manager.css', 'quiz-contract.js', 'quiz-manager.js', 'quiz-publish.js']:
            source = source.replace('./' + asset, './teacher/' + asset)
    else:
        for asset in ['quiz-types.css', 'quiz-types.js']:
            source = source.replace('./' + asset, './pupil/' + asset)
    source = source.replace('./vendor/', f'./{page}/vendor/')
    return '<!-- Generated by scripts/prepare-pages.py; edit the source page. -->\n' + source


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('page', choices=['pupil', 'teacher'])
    parser.add_argument('destination', type=Path)
    parser.add_argument('--environment', choices=['current', 'test'], default='current')
    parser.add_argument('--enable-quiz-manager', action='store_true', help='Prepare approved LIVE activation locally; does not deploy')
    parser.add_argument('--test-config', type=Path, help='Public test-project JSON; required for test')
    parser.add_argument('--test-captcha-site-key', help='Public Turnstile site key for TEST teacher only')
    args = parser.parse_args()
    if args.test_captcha_site_key and (args.environment != 'test' or args.page != 'teacher'
            or args.test_captcha_site_key.startswith(('sb_', 'sk_', 'eyJ'))
            or not re.fullmatch(r'[A-Za-z0-9_-]{10,200}', args.test_captcha_site_key)):
        parser.error('A public CAPTCHA site key requires a TEST teacher package')
    if (args.environment == 'test') != bool(args.test_config):
        parser.error('--environment test and --test-config must be used together')
    if args.enable_quiz_manager and args.environment != 'current':
        parser.error('--enable-quiz-manager is for the current LIVE package only; TEST already enables it')
    override = None
    if args.test_config:
        try:
            override = test_config(args.test_config)
        except (OSError, ValueError) as error:
            parser.error(str(error))
    destination = args.destination.resolve()
    if destination == ROOT or ROOT in destination.parents and 'work' not in destination.relative_to(ROOT).parts:
        parser.error('Use a separate staging directory or work/; do not overwrite source files')
    destination.mkdir(parents=True, exist_ok=True)
    for folder in [args.page, 'shared']:
        shutil.copytree(ROOT / folder, destination / folder, dirs_exist_ok=True)
    if override is not None:
        (destination / 'shared/config.js').write_text(override)
        # TEST must never inherit the LIVE widget, including when CAPTCHA is off.
        (destination / 'shared/auth-captcha.js').write_text(
            'window.HISTORY_CAPTCHA = Object.freeze({});\n')
    live_url = 'https://inxsjdogxvqbvxydxmym.supabase.co'
    if args.environment == 'test' or args.enable_quiz_manager:
        project_url = json.loads(args.test_config.read_text())['supabaseUrl'].rstrip('/') if override else live_url
        if args.enable_quiz_manager:
            source_config = (ROOT / 'shared/config.js').read_text()
            if not re.search(r'supabaseUrl:\s*"' + re.escape(live_url) + r'"', source_config):
                parser.error('LIVE activation requires the verified LIVE Supabase project')
            if 'https://monob26.github.io/history-teacher-dashboard/' not in source_config:
                parser.error('LIVE activation requires the existing teacher redirect')
        release = {'quizManager': True, 'projectUrl': project_url,
                   'pupilHomepageUrl': 'https://monob26.github.io/gcse-history-homework-hub-test/' if override else 'https://monob26.github.io/gcse-history-homework-hub/'}
        (destination / 'shared/release.js').write_text('window.HISTORY_RELEASE = Object.freeze(' + json.dumps(release, indent=2) + ');\n')
    else:
        # Source may be an activated deployed tree. Default staging stays a legacy fixture;
        # production activation always requires the explicit release option above.
        (destination / 'shared/release.js').write_text('window.HISTORY_RELEASE = Object.freeze({quizManager:false});\n')
    generated = entry(args.page)
    if override:
        live_origin = re.search(r'supabaseUrl:\s*"([^"]+)"', (ROOT / 'shared/config.js').read_text()).group(1)
        test_origin = json.loads(args.test_config.read_text())['supabaseUrl'].rstrip('/')
        for page_file in [destination / args.page / 'index.html']:
            page_file.write_text(page_file.read_text().replace('connect-src ' + live_origin, 'connect-src ' + test_origin))
        generated = generated.replace('connect-src ' + live_origin, 'connect-src ' + test_origin)
    if args.test_captcha_site_key:
        captcha_config = {'provider': 'turnstile', 'siteKey': args.test_captcha_site_key}
        (destination / 'shared/auth-captcha.js').write_text(
            'window.HISTORY_CAPTCHA = Object.freeze(' + json.dumps(captcha_config) + ');\n')
        provider = 'https://challenges.cloudflare.com'
        def captcha_policy(html):
            # Replace each existing directive: source may already allow LIVE Turnstile.
            html = re.sub(r"script-src [^;]+;", "script-src 'self' " + provider + ";", html)
            html = re.sub(r'connect-src [^;]+;',
                          'connect-src ' + test_origin + ' ' + provider + ';', html)
            html = re.sub(r'frame-src [^;]+;\s*', '', html)
            return html.replace('img-src', 'frame-src ' + provider + '; img-src')
        page_file = destination / args.page / 'index.html'
        page_file.write_text(captcha_policy(page_file.read_text()))
        generated = captcha_policy(generated)
    (destination / 'index.html').write_text(generated)
